#!/usr/bin/env python3
"""The board's numbers the Python driver and the register script need at run time, from the build's
arithmetic (one source of truth: sim/budget.py, and sim/wifi_channels.py for the fast arm's noise
bandwidth), as a small module that travels with the driver to the PYNQ, where build/ is not.

    python3 gateware/gen_constants.py      writes gateware/board_constants.py

The build's gateware step runs it after the budget and the analyses; driver/test_sim.py checks the
driver against build/budget.json, so a hand edit of the module, or a budget change not rebuilt, fails.
"""
import json, math, os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
B = json.load(open(os.path.join(ROOT, "build", "budget.json")))
P = B["parts"]
W = json.load(open(os.path.join(ROOT, "build", "wifi_channels.json")))
TODAY = [r for r in W if r.get("channel_MHz", 0) is None][0]          # the board as built: the arm's own pole, no filter

C = [
    ("# the received level: sim/budget.py sections 2 and 3", None),
    ("RX_GAIN_DB", (round(B["G_rf_dB"], 3), "RX ANT to the demodulator's input, the DSA at 0 dB: LNA - DSA's loss + 2 x ADL5611")),
    ("DEM_REG_DBM", (B["dem_target_dBm"], "the demodulator's input at the regulated level ...")),
    ("A_REG_V", (round(B["a_reg_V"], 5), "... where the fast arm's peak a, differential at the comparators, is this")),
    ("DSA_POWER_UP_DB", (P["dsa_max_dB"], "the PE43711 starts at its maximum in serial mode (its datasheet, 'Power-up control')")),
    ("V_MID", (B["V_mid"], "the arms' and the comparators' centre (section 7)")),
    ("# the interference survey: sections 3 and 7b; the fast arm's ENBW from sim/wifi_channels.py (the ADL5380 and the arm)", None),
    ("G_SLOW", (B["G_slow"], "the slow stage after the fast arm")),
    ("NF_CHAIN_DB", (round(B["nf_chain_dB"], 3), "the receiver's noise figure at RX ANT")),
    ("ENBW_SLOW_HZ", (B["B_slow_MHz"] * 1e6, "the slow path's noise bandwidth, budgeted")),
    ("ENBW_FAST_HZ", (round(TODAY["enbw_MHz"], 2) * 1e6, "the fast arm's, " + TODAY["case"])),
    ("# the interference detectors (sheet 6): section 8b and the AD8310's datasheet", None),
    ("AD8310_SLOPE_V_DB", (P["log_slope_V_dB"], "24 mV/dB at 10-200 MHz")),
    ("AD8310_INTERCEPT_DBV", (P["log_intercept_dBV"], "a sine's intercept")),
    ("LOG_TAP_DB", (round(-20 * math.log10(B["det_tap"]), 4), "the series resistors against its 1 k input: the share of the arm it sees")),
    ("V5_DIV", (B["v5_div"], "V5_MON = +5V_RF x this")),
    ("NTC_B", (P["ntc_B"], "the thermistor")),
    ("NTC_R25", (P["ntc_R25_ohm"], "")),
    ("NTC_RTOP", (B["ntc_Rtop"], "its pull-up from +3V3_DIG")),
    ("NTC_VDD", (3.3, "")),
    ("# the synthesizers: section 8", None),
    ("RSET_OHM", (P["pll_rset_ohm"], "the MAX2871's RSET")),
    ("CP_CODE", (P["pll_cp_code"], "ICP = 1.63 / RSET x (1 + CP)")),
]


def module():
    L = ['"""The board\'s numbers for the driver and gateware/max2871_regs.py.',
         "GENERATED by gateware/gen_constants.py from build/budget.json and build/wifi_channels.json: do not edit;",
         'change sim/budget.py and run `python3 build.py budget` (or `--only gateware` after the budget)."""']
    for name, v in C:
        if v is None:
            L.append(name)
            continue
        val, why = v
        L.append("%s = %r%s" % (name, val, ("    # " + why) if why else ""))
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    out = os.path.join(HERE, "board_constants.py")
    open(out, "w").write(module())
    print("wrote", os.path.relpath(out, ROOT))
